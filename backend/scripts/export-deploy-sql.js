// Writes sql/praise_deploy.sql: everything `npm run setup-db` does, as one plain SQL file for
// uploading to a server (phpMyAdmin, mysql CLI) where Node cannot run. Built from the same schema
// and seed files, so regenerate it after changing them: npm run export-deploy-sql
//
// Like setup-db it is safe to run again: tables are created only if missing, columns and indexes
// are added only if missing, seed rows use INSERT IGNORE, and each one-time step is recorded in
// praise_setup_steps so it never undoes later Access Management edits.
const fs = require('node:fs')
const path = require('node:path')
const { format } = require('mysql2')
const {
  accessRoles,
  nominatingRoleCodes,
  secretariatAwardingPermissions,
  secretariatCategoryPermissions,
  secretariatCommitteePermissions,
  secretariatRecordsPermissions,
  secretariatScreeningPermissions,
  secretariatValidationPermissions,
} = require('./accessSeed')
const { awardCategories, awardCycles } = require('./awardSeed')
const { awardingColumns } = require('./awardingColumns')
const { emisBrandingColumns } = require('./emisBrandingColumns')
const { cycleBudgetColumn, releaseColumns, releaseTables } = require('./releaseColumns')

const out = []
const sql = (text, values) => out.push(values ? format(text, values) : text)
const section = (title) => out.push('', `-- ${'-'.repeat(70)}`, `-- ${title}`, `-- ${'-'.repeat(70)}`)

// MySQL has no "ADD COLUMN IF NOT EXISTS", so the ALTER runs through a prepared statement only
// when information_schema says it is missing.
function alterIfMissing(existsQuery, alter) {
  sql(`SET @missing = (${existsQuery}) = 0;`)
  sql('SET @stmt = IF(@missing, ?, \'DO 0\');', [alter])
  sql('PREPARE s FROM @stmt; EXECUTE s; DEALLOCATE PREPARE s;')
}

// Runs the statements only the first time, like the praise_setup_steps checks in setup-db.
function oneTimeStep(name, statements) {
  const notDone = format('NOT EXISTS (SELECT 1 FROM praise_setup_steps WHERE name = ?)', [name])
  for (const statement of statements) sql(statement.replace('{NOT_DONE}', notDone))
  sql('INSERT IGNORE INTO praise_setup_steps (name) VALUES (?);', [name])
}

function grant(roleCodes, keys, onlyWhen = '{NOT_DONE}') {
  return keys.map((key) =>
    format(
      `INSERT IGNORE INTO praise_role_permissions (role_id, permission_key) SELECT id, ? FROM praise_access_roles WHERE code IN (?) AND ${onlyWhen};`,
      [key, roleCodes],
    ),
  )
}

sql('-- PRAISE deployment script. Generated by backend/scripts/export-deploy-sql.js; do not edit by hand.')
sql('-- Run it while the EMIS database is selected (USE <emis database>;). It needs the EMIS tables')
sql('-- users, reference_sections and emis_agency_setup. It creates no EMIS table; the only EMIS change')
sql('-- is adding PRAISE branding columns to emis_agency_setup (section 2), which EMIS can share.')
sql('SET NAMES utf8mb4;')

section('1. Tables (sql/praise_schema.sql)')
sql(fs.readFileSync(path.join(__dirname, '..', 'sql', 'praise_schema.sql'), 'utf8').trim())

section('2. Columns and indexes added after the first release')
const tableHas = (table, kind, name) =>
  kind === 'index'
    ? format('SELECT COUNT(*) FROM information_schema.statistics WHERE table_schema = DATABASE() AND table_name = ? AND index_name = ?', [table, name])
    : format('SELECT COUNT(*) FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = ? AND column_name = ?', [table, name])
alterIfMissing(tableHas('praise_award_categories', 'index', 'uq_category_name'), 'ALTER TABLE praise_award_categories ADD UNIQUE KEY uq_category_name (name)')
alterIfMissing(tableHas('praise_nomination_documents', 'column', 'criterion'), 'ALTER TABLE praise_nomination_documents ADD COLUMN criterion VARCHAR(40) NULL AFTER doc_type')
alterIfMissing(tableHas('praise_award_categories', 'column', 'criteria_weights'), 'ALTER TABLE praise_award_categories ADD COLUMN criteria_weights JSON NULL AFTER is_active')
sql("SET @backfill_created_by = (SELECT COUNT(*) FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = 'praise_nominations' AND column_name = 'created_by') = 0;")
alterIfMissing(
  "SELECT COUNT(*) FROM information_schema.columns WHERE table_schema = DATABASE() AND table_name = 'praise_nominations' AND column_name = 'status' AND column_type LIKE '%''closed''%'",
  "ALTER TABLE praise_nominations MODIFY COLUMN status ENUM('draft', 'submitted', 'validated', 'disqualified', 'closed', 'shortlisted', 'not_selected', 'endorsed', 'awarded') NOT NULL DEFAULT 'draft'",
)
sql(format('SET @new_sort = (?) = 0;', [tableHas('praise_award_categories', 'column', 'sort_order')].map((q) => ({ toSqlString: () => q }))))
alterIfMissing(tableHas('praise_award_categories', 'column', 'sort_order'), 'ALTER TABLE praise_award_categories ADD COLUMN sort_order INT NOT NULL DEFAULT 0 AFTER criteria_weights')
sql('UPDATE praise_award_categories SET sort_order = id WHERE @new_sort;')
alterIfMissing(tableHas('praise_screening_scores', 'column', 'remarks'), 'ALTER TABLE praise_screening_scores ADD COLUMN remarks TEXT NULL AFTER scores')
alterIfMissing(tableHas('praise_nominations', 'column', 'created_by'), 'ALTER TABLE praise_nominations ADD COLUMN created_by VARCHAR(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NULL AFTER nominator_name')
sql('UPDATE praise_nominations SET created_by = nominator_employee_id WHERE created_by IS NULL AND @backfill_created_by;')
alterIfMissing(tableHas('praise_award_cycles', 'column', 'ceremony_date'), 'ALTER TABLE praise_award_cycles ADD COLUMN ceremony_date DATE NULL AFTER nomination_end')
for (const [name, definition] of awardingColumns) {
  alterIfMissing(tableHas('praise_nominations', 'column', name), `ALTER TABLE praise_nominations ADD COLUMN \`${name}\` ${definition}`)
}
for (const table of releaseTables) {
  for (const [name, definition] of releaseColumns) {
    alterIfMissing(tableHas(table, 'column', name), `ALTER TABLE ${table} ADD COLUMN \`${name}\` ${definition}`)
  }
}
alterIfMissing(
  tableHas('praise_award_cycles', 'column', cycleBudgetColumn[0]),
  `ALTER TABLE praise_award_cycles ADD COLUMN \`${cycleBudgetColumn[0]}\` ${cycleBudgetColumn[1]}`,
)
for (const column of emisBrandingColumns) {
  alterIfMissing(tableHas('emis_agency_setup', 'column', column.name), `ALTER TABLE emis_agency_setup ADD COLUMN \`${column.name}\` ${column.definition}`)
}
sql('INSERT IGNORE INTO emis_agency_setup (id) VALUES (1);')

section('3. Award categories, levels and cycles')
for (const { tiers, behavioral_indicators, ...category } of awardCategories) {
  // Levels are only added with a new award, so ones later renamed or removed stay that way.
  sql('SET @is_new = NOT EXISTS (SELECT 1 FROM praise_award_categories WHERE code = ?);', [category.code])
  sql('INSERT IGNORE INTO praise_award_categories SET ?;', [{ ...category, behavioral_indicators: JSON.stringify(behavioral_indicators) }])
  for (const tier of tiers) {
    const columns = Object.keys(tier)
    sql(
      `INSERT IGNORE INTO praise_award_category_tiers (category_id, ${columns.join(', ')}) SELECT id, ? FROM praise_award_categories WHERE code = ? AND @is_new;`,
      [Object.values(tier), category.code],
    )
  }
}
for (const cycle of awardCycles) sql('INSERT IGNORE INTO praise_award_cycles SET ?;', [cycle])

section('4. Access roles and their starting permissions')
for (const { permissions, ...role } of accessRoles) {
  // Permissions are only seeded when a role is first created, so later edits are kept.
  sql('SET @is_new = NOT EXISTS (SELECT 1 FROM praise_access_roles WHERE code = ?);', [role.code])
  sql('INSERT IGNORE INTO praise_access_roles SET ?;', [role])
  for (const statement of grant([role.code], permissions, '@is_new')) sql(statement)
}

section('5. One-time permission upgrades for databases created by older versions')
const onlySecretariat = ['award_categories.create', 'award_categories.manage_inactive']
oneTimeStep('secretariat_category_permissions', [
  ...grant(['secretariat'], secretariatCategoryPermissions),
  format(
    "DELETE p FROM praise_role_permissions p JOIN praise_access_roles r ON r.id = p.role_id WHERE r.code <> 'secretariat' AND p.permission_key IN (?) AND {NOT_DONE};",
    [onlySecretariat],
  ),
  format('DELETE FROM praise_user_permission_overrides WHERE permission_key IN (?) AND is_allowed = 1 AND {NOT_DONE};', [onlySecretariat]),
])
oneTimeStep('secretariat_validation_permissions', grant(['secretariat'], secretariatValidationPermissions))
oneTimeStep('committee_permissions', [...grant(['secretariat'], secretariatCommitteePermissions), ...grant(['committee'], ['committee'])])
oneTimeStep('screening_permissions', [...grant(['secretariat'], secretariatScreeningPermissions), ...grant(['committee'], ['screening'])])
oneTimeStep('committee_can_nominate', grant(nominatingRoleCodes, ['nominations', 'nominations.create']))
oneTimeStep('awarding_permissions', grant(['secretariat'], secretariatAwardingPermissions))
oneTimeStep('records_permissions', grant(['secretariat'], secretariatRecordsPermissions))

const target = path.join(__dirname, '..', 'sql', 'praise_deploy.sql')
fs.writeFileSync(target, `${out.join('\n')}\n`)
console.log(`Wrote ${path.relative(process.cwd(), target)}`)
